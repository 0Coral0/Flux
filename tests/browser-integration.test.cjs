const { test } = require('node:test');
const assert = require('node:assert/strict');
const { readFileSync } = require('node:fs');
const vm = require('node:vm');
const source = readFileSync(`${__dirname}/../js/browser.js`, 'utf8');

function setup({ origin = null, site = 'https://flux.example/', active = true, responses = [] } = {}) {
  const state = { active, assignments: [], responses, timer: null, activate: null };
  const frame = { hidden: true, set src(value) { state.assignments.push(value); this._src = value; }, get src() { return this._src; } };
  const tools = { hidden: true };
  const message = { hidden: true };
  const external = {};
  const elements = {
    'view-browser': { classList: { contains: () => state.active } },
    'flux-browser-frame': frame, 'flux-browser-setup': message,
    'flux-browser-tools': tools, 'flux-browser-external': external,
  };
  const context = {
    URL, JSON, location: new URL(site), window: { FLUX_BROWSER_ORIGIN: origin },
    document: { hidden: false, getElementById: id => elements[id], addEventListener() {} },
    MutationObserver: class { constructor(callback) { state.activate = callback; } observe() {} },
    setInterval: callback => { state.timer = callback; },
    fetch: async () => {
      const response = state.responses.shift();
      if (response instanceof Error) throw response;
      return response === undefined ? { ok: false } : { ok: true, text: async () => response };
    },
  };
  vm.runInNewContext(source, context);
  return { state, context, frame, tools, message, external };
}
const settle = () => new Promise(resolve => setImmediate(resolve));

test('opens a separate HTTPS origin and exposes a direct sign-in fallback', async () => {
  const h = setup({ origin: 'https://proxy.example/anything?token=ignored#fragment' });
  await settle();
  assert.equal(h.frame.src, 'https://proxy.example/?embed=1');
  assert.equal(h.external.href, 'https://proxy.example/');
  assert.equal(h.frame.hidden, false);
  assert.equal(h.tools.hidden, false);
});

test('rejects same-origin, unencrypted, and credential-bearing proxy URLs', async () => {
  for (const origin of ['https://flux.example/', 'http://proxy.example/', 'https://user:pass@proxy.example/']) {
    const h = setup({ origin });
    await settle();
    assert.equal(h.frame.hidden, true);
    assert.equal(h.message.hidden, false);
    assert.equal(h.tools.hidden, true);
  }
});

test('keeps a working browser when refresh fails and switches when the address changes', async () => {
  const h = setup({ origin: 'https://old.example', responses: [new Error('offline')] });
  await settle();
  assert.deepEqual(h.state.assignments, ['https://old.example/?embed=1']);
  h.state.responses.push('// Generated by the launcher\nwindow.FLUX_BROWSER_ORIGIN = "https://new.example";\n');
  await h.state.timer();
  assert.deepEqual(h.state.assignments, ['https://old.example/?embed=1', 'https://new.example/?embed=1']);
  assert.equal(h.external.href, 'https://new.example/');
  h.state.responses.push('window.FLUX_BROWSER_ORIGIN = "https://new.example";\n');
  await h.state.timer();
  assert.equal(h.state.assignments.length, 2);
});

test('does not execute code fetched with a published address', async () => {
  const h = setup({ origin: 'https://old.example', responses: ['window.FLUX_BROWSER_ORIGIN = "https://new.example";\nwindow.executed = true;'] });
  await settle();
  assert.equal(h.frame.src, 'https://new.example/?embed=1');
  assert.equal(h.context.window.executed, undefined);
});

test('uses the local proxy when Flux runs locally without a configured address', async () => {
  const h = setup({ site: 'http://127.0.0.1:3031/' });
  await settle();
  assert.equal(h.frame.src, 'http://127.0.0.1:3040/?embed=1');
});
